def get_special_order(name: str) -> dict:
    """📋 按任务名查特别任务详情（岛屿食材/深处的危险…）。无则 None。"""
    return SPECIAL_ORDERS.get(name)


def special_orders_available(kw: str = "") -> str:
    """📋 搜索特别任务知识库（kw=关键词；空=全部）。返回可读文本。"""
    try:
        kws = [k for k in (kw or "").replace("，", " ").replace(",", " ").split() if k]
        lines = []
        for name, o in SPECIAL_ORDERS.items():
            hay = name + o.get("requester", "") + o.get("need", "") + o.get("reward", "") + o["req_en"]
            if kws and not all(k in hay for k in kws):
                continue
            board = "🏘️镇" if o["board"] == "town" else "🥥齐"
            lines.append(f"[{board}] {name}（{o['requester']}·{o['dur']}·{o['prereq']}）")
            lines.append(f"   需求：{o['need']}")
            lines.append(f"   奖励：{o['reward']}（{o['repeat']}；交付点看 map_query）")
        return "\n".join(lines) if lines else f"📋 没有「{kw}」相关特别任务。查：岛屿食材/历史的碎片/皮埃尔优选/深处的危险…"
    except Exception as e:
        return f"❌ {e}"
