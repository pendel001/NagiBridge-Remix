def build_calendar_line(season: str, day: int, day_index: int, year: int = 1) -> str:
    """构建一行日历信息，给状态注入用。"""
    parts = []

    # 节日
    festival = FESTIVALS.get((season.lower(), day))
    if festival:
        # 取第一段 emoji+名字
        short = festival.split("—")[0].strip()
        parts.append(short)

    # 生日
    birthday = BIRTHDAYS.get((season.lower(), day))
    if birthday:
        parts.append(f"🎂{birthday}")

    # 商店休息
    closed = get_closed_shops_today_v2(day_index)
    if closed:
        parts.append(f"🏪休: {', '.join(closed)}")

    return " | ".join(parts) if parts else ""


