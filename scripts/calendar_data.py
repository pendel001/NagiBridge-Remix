_SEASONS = ["spring", "summer", "fall", "winter"]


def _festival_short(detail: str) -> str:
    """节日名：去掉 emoji 前缀 + "— 地点时间"（与 build_calendar_line 同款，但剥掉 emoji）。"""
    short = detail.split("—")[0].strip()
    for i, ch in enumerate(short):
        if '一' <= ch <= '鿿':  # 只认 CJK 汉字，emoji 不在这个范围
            return short[i:]
    return short


def get_festival_today(season: str, day: int) -> dict | None:
    """今天有没有节日。返回 {name, map, detail} 或 None。"""
    key = (season.lower(), int(day))
    detail = FESTIVALS.get(key)
    if not detail:
        return None
    return {"name": _festival_short(detail), "map": FESTIVAL_LOCATIONS.get(key), "detail": detail}


def get_festival_tomorrow(season: str, day: int) -> dict | None:
    """明天有没有节日（28 天/月，月底跨季节）。返回同上或 None。"""
    day = int(day)
    if day < 28:
        return get_festival_today(season, day + 1)
    next_season = {"spring": "summer", "summer": "fall", "fall": "winter", "winter": "spring"}.get(season.lower(), season)
    return get_festival_today(next_season, 1)


def get_next_festival(season: str, day: int) -> dict | None:
    """今天之后最近的节日（按 春→夏→秋→冬 顺序）。返回 {name, season, day, map, detail, days_left} 或 None。"""
    try:
        cur = _SEASONS.index(season.lower())
    except ValueError:
        return None
    day = int(day)
    candidates = sorted((_SEASONS.index(s), d, (s, d), detail) for (s, d), detail in FESTIVALS.items())
    for si, d, key, detail in candidates:
        if si > cur or (si == cur and d > day):
            days = d - day if si == cur else (28 - day + d) + 28 * (si - cur - 1)
            return {
                "name": _festival_short(detail), "season": _SEASONS[si], "day": d,
                "map": FESTIVAL_LOCATIONS.get(key), "detail": detail, "days_left": days,
            }
    # 今天之后没有了（跨年）→ 下一年第一个
    if candidates:
        si, d, key, detail = candidates[0]
        days = (28 - day) + d + 28 * (len(_SEASONS) - 1 - cur)  # 粗略跨年天数
        return {
            "name": _festival_short(detail), "season": _SEASONS[si], "day": d,
            "map": FESTIVAL_LOCATIONS.get(key), "detail": detail, "days_left": days, "next_year": True,
        }
    return None

