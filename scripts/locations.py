# ── 查路线工具 ──
def plan_route(from_map, to_poi):
    """返回: [ (地图名, 目的坐标, 说明), ... ]"""
    if to_poi in POI:
        target = POI[to_poi]
        to_map = target["map"]
        to_pos = target["pos"]
    else:
        to_map = to_poi
        to_pos = None

    if from_map == to_map:
        return [(to_map, to_pos, "已在地图上")]

    # BFS 搜地图连接
    graph = {}
    for src, _, dst, _ in ROUTES:
        graph.setdefault(src, set()).add(dst)
        graph.setdefault(dst, set()).add(src)

    visited = {from_map}
    queue = [(from_map, [from_map])]
    while queue:
        cur, path = queue.pop(0)
        for nxt in graph.get(cur, set()):
            if nxt == to_map:
                route = []
                for m in path[1:] + [to_map]:
                    entry = POI.get(m, {}).get("pos", None)
                    route.append((m, entry, f"到 {m}"))
                route.append((to_map, to_pos, f"到达 {to_poi}"))
                return route
            if nxt not in visited:
                visited.add(nxt)
                queue.append((nxt, path + [nxt]))
    return None

